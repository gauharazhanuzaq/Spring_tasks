create table if not exists artists (
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null,
    country     varchar(60),
    birth_year  integer,
    created_at  timestamp with time zone not null default now()
);

create table if not exists artworks (
    id            bigint generated by default as identity primary key,
    title         varchar(200) not null,
    created_year  integer,
    price         numeric(12,2),
    style         varchar(60),
    artist_id     bigint not null references artists(id),
    created_at    timestamp with time zone not null default now()
);
create index if not exists idx_artworks_artist on artworks(artist_id);
create index if not exists idx_artworks_style  on artworks(style);

create table if not exists exhibitions (
    id          bigint generated by default as identity primary key,
    title       varchar(200) not null,
    start_date  date not null,
    end_date    date not null,
    created_at  timestamp with time zone not null default now()
);

create table if not exists exhibition_artworks (
    exhibition_id bigint not null references exhibitions(id),
    artwork_id    bigint not null references artworks(id),
    primary key (exhibition_id, artwork_id)
);